// An io topology: the sources in one repository, the output in another.
const ioTopology = `# the sources apart from the output
platform: {url: https://git.example.org/okdp/okdp-sources.git}
projects: {url: https://git.example.org/okdp/okdp-sources.git, path: "projects/{project}"}
output:   {url: https://git.example.org/okdp/okdp-output.git}
`

// The workflow of the output, as it is written.
func TestTheWorkflowOfTheOutput(t *testing.T) {
	got, err := OutputWorkflow([]byte(ioTopology), nil)
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by okdp-gitops. Do not edit.
name: okdp-gitops
on:
  schedule:
    - cron: "*/2 * * * *"
  workflow_dispatch: {}
concurrency:
  group: okdp-gitops
  cancel-in-progress: false
jobs:
  compile:
    runs-on: okdp-gitops
    container:
      volumes: ["okdp-charts:/var/cache/okdp/charts"]
    steps:
      - name: okdp-gitops compile
        shell: sh
        env:
          GITOPS_TOKEN: ${{ secrets.OKDP_GITOPS_TOKEN }}
        run: |
          topology="$(mktemp)"
          printf %s '` + base64.StdEncoding.EncodeToString([]byte(ioTopology)) + `' | base64 -d > "$topology"
          okdp-gitops compile --config "$topology" --charts /var/cache/okdp/charts
`
	if string(got) != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

// The workflow runs the compile on its schedule, and on demand, never on
// a push, in a job of the runner of the contract, the chart cache
// mounted, the token the output repository's secret; its script writes
// the topology as it is, and gives it to okdp-gitops compile.
func TestTheWorkflowOfTheOutputCompilesOnASchedule(t *testing.T) {
	topology := "# a topology: 'quotes', \"double\", `$HOME` \\ and $(true)\n" +
		"platform: {url: 'https://git.example.org/okdp/okdp-platform.git'}\n\n" +
		"projects:\n  url: https://git.example.org/okdp/okdp-project-{project}.git\n" +
		"output:   {url: https://git.example.org/okdp/okdp-output.git}   \n"
	raw, err := OutputWorkflow([]byte(strings.ReplaceAll(topology, "\n", "\r\n")), nil)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(raw), GeneratedHeader+"\n") {
		t.Errorf("not marked generated:\n%s", raw)
	}
	// Parsed as the engines parse it (YAML 1.2): on is a key, not true.
	var doc struct {
		On          map[string]any `yaml:"on"`
		Concurrency struct {
			Group            string `yaml:"group"`
			CancelInProgress *bool  `yaml:"cancel-in-progress"`
		} `yaml:"concurrency"`
		Jobs map[string]struct {
			RunsOn    string `yaml:"runs-on"`
			Container struct {
				Image   string   `yaml:"image"`
				Volumes []string `yaml:"volumes"`
			} `yaml:"container"`
			Steps []struct {
				Shell string            `yaml:"shell"`
				Env   map[string]string `yaml:"env"`
				Run   string            `yaml:"run"`
			} `yaml:"steps"`
		} `yaml:"jobs"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("%v:\n%s", err, raw)
	}
	if len(doc.On) != 2 || doc.On["workflow_dispatch"] == nil || fmt.Sprint(doc.On["schedule"]) != "[map[cron:"+WorkflowSchedule+"]]" {
		t.Errorf("on: %v", doc.On)
	}
	if doc.Concurrency.Group != WorkflowConcurrencyGroup || doc.Concurrency.CancelInProgress == nil || *doc.Concurrency.CancelInProgress {
		t.Errorf("concurrency: %+v", doc.Concurrency)
	}
	job := doc.Jobs["compile"]
	if job.RunsOn != RunnerLabel || job.Container.Image != "" || strings.Join(job.Container.Volumes, ",") != RunnerChartVolume+":"+RunnerChartCache ||
		len(job.Steps) != 1 || job.Steps[0].Shell != "sh" || len(job.Steps[0].Env) != 1 || job.Steps[0].Env[TokenEnv] != "${{ secrets."+TokenSecret+" }}" {
		t.Fatalf("job: %+v", job)
	}

	// The script, okdp-gitops a stub that keeps its arguments and the
	// file of --config.
	dir := t.TempDir()
	stub := "#!/bin/sh\nprintf '%s\\n' \"$@\" > \"$OUT/args\"\ncp \"$3\" \"$OUT/topology\"\n"
	if err := os.WriteFile(filepath.Join(dir, "okdp-gitops"), []byte(stub), 0o755); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("sh", "-e", "-c", job.Steps[0].Run)
	cmd.Env = append(os.Environ(), "PATH="+dir+":"+os.Getenv("PATH"), "OUT="+dir)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%v: %s", err, out)
	}
	args, _ := os.ReadFile(filepath.Join(dir, "args"))
	lines := strings.Split(strings.TrimSpace(string(args)), "\n")
	if len(lines) != 5 || lines[0] != "compile" || lines[1] != "--config" || lines[3] != "--charts" || lines[4] != RunnerChartCache {
		t.Errorf("args: %q", lines)
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "topology")); string(got) != topology {
		t.Errorf("topology:\n%q\nwant:\n%q", got, topology)
	}
}

// A topology the job cannot use, or the workflow cannot hold, is refused.
func TestTheWorkflowRefusesATopologyTheJobCannotUse(t *testing.T) {
	for topology, want := range map[string]string{
		"platform: {url: ./platform}\nprojects: {url: './p-{project}'}\noutput: {url: ./out}\n":                                                                                     `platform.url "./platform": the job reaches its repositories over HTTP(S)`,
		"platform: {url: 'git@git.example.org:okdp/p.git'}\nprojects: {url: 'git@git.example.org:okdp/p-{project}.git'}\noutput: {url: 'git@git.example.org:okdp/o.git'}\n":         `platform.url "git@git.example.org:okdp/p.git": the job reaches`,
		"platform: {url: 'https://bot:s3cr3t@git.example.org/p.git'}\nprojects: {url: 'https://git.example.org/p-{project}.git'}\noutput: {url: 'https://git.example.org/o.git'}\n": "platform.url: a password in a URL would be committed",
		"platform: {url: https://git.example.org/p.git}\n": "projects.url is required",
	} {
		_, err := OutputWorkflow([]byte(topology), nil)
		if err == nil || !strings.HasPrefix(err.Error(), "the topology of the workflow: "+want) {
			t.Errorf("%q: %v", topology, err)
		}
	}
}

// A topology over http:// is the workflow's when its hosts are allowed
// (GITOPS_INSECURE_HTTP_HOSTS of okdp-gitops workflow), the job's
// environment then allowing those its URLs need; refused otherwise.
func TestTheWorkflowOfAnHTTPTopology(t *testing.T) {
	topology := "platform: {url: http://forgejo-http.forgejo.svc.cluster.local:3000/okdp/okdp-platform.git}\n" +
		"projects: {url: 'http://forgejo-http.forgejo.svc.cluster.local:3000/okdp/okdp-project-{project}.git'}\n" +
		"output: {url: https://git.example.org/okdp/okdp-output.git}\n"
	for _, hosts := range [][]string{nil, {"git.example.org"}, {"*.cluster.example"}} {
		if _, err := OutputWorkflow([]byte(topology), hosts); err == nil || !strings.Contains(err.Error(), "the topology of the workflow: platform.url \"http://forgejo-http.forgejo.svc.cluster.local:3000/okdp/okdp-platform.git\": the token of OKDP_GITOPS_TOKEN would go over http://, in clear, to forgejo-http.forgejo.svc.cluster.local: allow the host with GITOPS_INSECURE_HTTP_HOSTS") {
			t.Errorf("%q: %v", hosts, err)
		}
	}
	if _, err := OutputWorkflow([]byte(topology), []string{"*.svc.cluster.local", "a b"}); err == nil || !strings.Contains(err.Error(), `GITOPS_INSECURE_HTTP_HOSTS: "a b" is not a host name nor a glob of one`) {
		t.Errorf("a pattern the workflow cannot hold: %v", err)
	}

	raw, err := OutputWorkflow([]byte(topology), []string{"git.example.org", "*.svc.cluster.local", "*.svc.cluster.local"})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(raw), "\n          GITOPS_TOKEN: ${{ secrets.OKDP_GITOPS_TOKEN }}\n          GITOPS_INSECURE_HTTP_HOSTS: \"*.svc.cluster.local\"\n        run: |\n") {
		t.Errorf("the environment of the job:\n%s", raw)
	}
	var doc struct {
		Jobs map[string]struct {
			Steps []struct {
				Env map[string]string `yaml:"env"`
			} `yaml:"steps"`
		} `yaml:"jobs"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("%v:\n%s", err, raw)
	}
	if env := doc.Jobs["compile"].Steps[0].Env; len(env) != 2 || env[InsecureHTTPHostsEnv] != "*.svc.cluster.local" || env[TokenEnv] != "${{ secrets."+TokenSecret+" }}" {
		t.Errorf("env: %v", env)
	}

	https, err := OutputWorkflow([]byte(ioTopology), []string{"*.svc.cluster.local"})
	if err != nil || strings.Contains(string(https), InsecureHTTPHostsEnv) {
		t.Errorf("an https topology carries no host: %v\n%s", err, https)
	}
}

// The audit's probe of GIT-12: the topology is operator text, and YAML
// reads a lone CR, NEL, LS or PS as a line break, so a value broken by one
// ends the heredoc of the script (or, with the workflow's indentation, any
// block of it) and runs a command beside GITOPS_TOKEN. A control character
// but a line feed (and a tab) is refused, and the script holds the
// topology encoded, whatever it holds: ${{ and a line OKDP_TOPOLOGY
// included, YAML escapes or not.
func TestTheWorkflowNeverRunsAValueOfTheTopology(t *testing.T) {
	topology := func(owner string) string {
		return "platform: {url: https://git.example.org/p.git}\nprojects: {url: 'https://git.example.org/p-{project}.git'}\n" +
			"output: {url: https://git.example.org/o.git}\nforgejo: {url: https://f.example.org, tokenFile: /t, owner: " + owner + "}\n"
	}
	run := func(raw []byte) (pwned bool, written string) {
		t.Helper()
		var doc struct {
			Jobs map[string]struct {
				Steps []struct {
					Run string `yaml:"run"`
				} `yaml:"steps"`
			} `yaml:"jobs"`
		}
		if err := yaml.Unmarshal(raw, &doc); err != nil {
			t.Fatalf("the workflow does not parse: %v\n%s", err, raw)
		}
		dir := t.TempDir()
		stub := "#!/bin/sh\ncp \"$3\" \"" + dir + "/topology\"\n"
		if err := os.WriteFile(filepath.Join(dir, "okdp-gitops"), []byte(stub), 0o755); err != nil {
			t.Fatal(err)
		}
		cmd := exec.Command("sh", "-e", "-c", doc.Jobs["compile"].Steps[0].Run)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "PATH="+dir+":"+os.Getenv("PATH"))
		_ = cmd.Run()
		_, err := os.Stat(filepath.Join(dir, "pwned"))
		got, _ := os.ReadFile(filepath.Join(dir, "topology"))
		return err == nil, string(got)
	}
	for name, brk := range map[string]string{"CR": "\r", "NEL": "\u0085", "LS": "\u2028", "PS": "\u2029", "NUL": "\x00", "ESC": "\x1b", "DEL": "\x7f"} {
		raw, err := OutputWorkflow([]byte(topology(`"a`+brk+`          OKDP_TOPOLOGY`+brk+`          touch pwned`+brk+`          b"`)), nil)
		if err == nil {
			pwned, _ := run(raw)
			t.Errorf("%s: a control character in the topology is accepted (a command ran: %v)", name, pwned)
			continue
		}
		if !strings.HasPrefix(err.Error(), "the topology of the workflow: ") || !strings.Contains(err.Error(), "control character") {
			t.Errorf("%s: %v", name, err)
		}
	}

	// Anything else is carried as it is, escapes of YAML included.
	for name, owner := range map[string]string{
		"an expression":        `"$\x7b{ secrets.OKDP_GITOPS_TOKEN }}"`,
		"a literal expression": `'${{ secrets.OKDP_GITOPS_TOKEN }}'`,
		"the terminator":       `"a\nOKDP_TOPOLOGY\ntouch pwned\nb"`,
		"quotes and a tab":     "'it''s\ta $(touch pwned) `touch pwned`'",
	} {
		text := topology(owner)
		raw, err := OutputWorkflow([]byte(text), nil)
		if err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		if n := strings.Count(string(raw), "${{"); n != 1 {
			t.Errorf("%s: %d expressions in the workflow, want the token's only:\n%s", name, n, raw)
		}
		if pwned, got := run(raw); pwned || got != text {
			t.Errorf("%s: a command ran (%v), or the topology is %q, want %q", name, pwned, got, text)
		}
	}
}

// With a CA bundle of the platform's own, the job mounts its directory
// read-only and trusts the file: the runner lets the directory in.
func TestTheWorkflowMountsTheCABundle(t *testing.T) {
	got, err := OutputWorkflowWith([]byte(ioTopology), WorkflowOptions{CAFile: "/etc/okdp/ca/ca.crt"})
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Jobs map[string]struct {
			Container struct {
				Volumes []string `yaml:"volumes"`
			} `yaml:"container"`
			Steps []struct {
				Env map[string]string `yaml:"env"`
			} `yaml:"steps"`
		} `yaml:"jobs"`
	}
	if err := yaml.Unmarshal(got, &doc); err != nil {
		t.Fatalf("%v:\n%s", err, got)
	}
	job := doc.Jobs["compile"]
	if v := strings.Join(job.Container.Volumes, " "); v != "okdp-charts:/var/cache/okdp/charts /etc/okdp/ca:/etc/okdp/ca:ro" {
		t.Errorf("volumes: %q", v)
	}
	if e := job.Steps[0].Env; len(e) != 2 || e["SSL_CERT_FILE"] != "/etc/okdp/ca/ca.crt" || e[TokenEnv] == "" {
		t.Errorf("env: %v", e)
	}
}

// A CA file the volume entry, YAML or the shell could read otherwise, or
// whose directory is the root, is refused.
func TestTheWorkflowRefusesACAFileItCannotHold(t *testing.T) {
	for _, file := range []string{"ca.crt", "/ca.crt", "/etc/okdp/ca/", "/etc/okdp/../ca.crt", "/etc/okdp//ca.crt", "/etc/okdp/ca.crt:ro",
		"/etc/okdp/c a.crt", "/etc/okdp/ca\".crt", "/etc/okdp/ca$(x).crt", "/etc/okdp/ca\n.crt"} {
		_, err := OutputWorkflowWith([]byte(ioTopology), WorkflowOptions{CAFile: file})
		if err == nil || !strings.HasPrefix(err.Error(), RunnerCAFileEnv+": ") {
			t.Errorf("%q: %v", file, err)
		}
	}
}
