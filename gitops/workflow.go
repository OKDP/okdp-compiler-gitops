// The CI of the output: a Forgejo Actions workflow in the output
// repository runs okdp-gitops compile on a schedule (WorkflowSchedule),
// and on demand, in a job of its own, on a runner dedicated to it, which
// this contract describes:
//
//   - its label is RunnerLabel, which the runner maps to the okdp-gitops
//     image on its docker executor (okdp-gitops:docker://<image>): each
//     job runs in a new container of the image, removed after it, with
//     nothing of the runner's, its shell the image's (sh);
//   - the Docker volume RunnerChartVolume is one the runner lets a job
//     mount (container.valid_volumes), writable by the image's user: the
//     workflow mounts it at RunnerChartCache, the chart cache of the
//     checks;
//   - when the repositories are served over https with a CA of the
//     platform's own, the runner also lets a job mount the directory of
//     that CA bundle (container.valid_volumes), read-only, and the workflow
//     says where it is (WorkflowOptions.CAFile): the job's SSL_CERT_FILE;
//   - the runner is registered for the output repository only, and holds
//     no credentials: the workflow carries the topology, and the output
//     repository's secret TokenSecret, a token that reads the sources and
//     writes the output, is the job's TokenEnv (CredentialsFromEnv).
//
// The repositories of the sources, the platform's and the projects', hold
// no workflow and no token: a writer of one could otherwise read the token
// from a workflow of their own and push the output, which the engines
// deploy with every right. A commit of the sources is compiled by the next
// run of the schedule; a run whose sources did not move since the last
// compile writes nothing.
const (
	// WorkflowPath is the workflow in the output repository, on its
	// default branch (the branch Forgejo runs a schedule of).
	WorkflowPath = ".forgejo/workflows/okdp-gitops.yaml"
	// WorkflowSchedule is the cron schedule of the workflow: every 2
	// minutes, the delay between a commit of the sources and its compile.
	WorkflowSchedule = "*/2 * * * *"
	// WorkflowConcurrencyGroup is the concurrency group of the workflow
	// (Forgejo's workflow-level concurrency): a run waits for the one of
	// the group before it, never cancels it, so that a compile is not
	// cut short between its reads and its push.
	WorkflowConcurrencyGroup = "okdp-gitops"
	// RunnerLabel is the label of the runners of the workflow.
	RunnerLabel = "okdp-gitops"
	// RunnerChartVolume is the Docker volume of the chart cache.
	RunnerChartVolume = "okdp-charts"
	// RunnerChartCache is where the job mounts RunnerChartVolume.
	RunnerChartCache = "/var/cache/okdp/charts"
	// RunnerCAFileEnv is the environment variable of okdp-gitops workflow
	// that names WorkflowOptions.CAFile.
	RunnerCAFileEnv = "GITOPS_RUNNER_CA_FILE"
	// TokenSecret is the secret of the output repository that the job
	// reads its token from (TokenEnv): the only token of the CI.
	TokenSecret = "OKDP_GITOPS_TOKEN"
)

// GeneratedHeader is the first line of a file okdp-gitops writes.
const GeneratedHeader = "# Generated by okdp-gitops. Do not edit."

// OutputWorkflow is the workflow of the output repository: on the
// schedule WorkflowSchedule, and on demand, okdp-gitops compile of the
// whole tree that topology (a topology file) describes, its values checked
// against the upstream charts. The job writes the topology to a file of
// its own, and authenticates to its repositories with the output
// repository's secret TokenSecret: a topology of local directories, or of
// other repositories than HTTP(S) ones, or that holds credentials (a URL's
// password) or a control character but a line feed and a tab (YAML reads
// a lone CR, NEL, LS or PS as a line break), is refused. The script holds
// the topology base64 encoded, never as text of its own: nothing in it is
// read by the shell, by YAML or by Forgejo's expressions. The token goes over
// http:// only to the hosts insecureHTTPHosts allows (hosts or globs,
// InsecureHTTPHosts, the GITOPS_INSECURE_HTTP_HOSTS of okdp-gitops
// workflow): a topology with an http:// URL of another host is refused,
// and the job's environment carries, as InsecureHTTPHostsEnv, those of
// insecureHTTPHosts its http:// URLs need.
func OutputWorkflow(topology []byte, insecureHTTPHosts []string) ([]byte, error) {
	return OutputWorkflowWith(topology, WorkflowOptions{InsecureHTTPHosts: insecureHTTPHosts})
}

// WorkflowOptions is what the environment of the output's job carries
// beside its token (OutputWorkflowWith).
type WorkflowOptions struct {
	// InsecureHTTPHosts are the hosts or globs the token goes to over
	// http:// (OutputWorkflow's insecureHTTPHosts): those the topology's
	// http:// URLs need are the job's InsecureHTTPHostsEnv.
	InsecureHTTPHosts []string
	// PrivateChartHosts are the chart hosts the job's chart puller
	// reaches at a private address (a registry of the cluster), as
	// ChartHosts takes them: the job's PrivateChartHostsEnv, all of them.
	PrivateChartHosts []string
	// InsecureChartHosts are the chart hosts the job's chart puller
	// reaches over plain HTTP, as ChartHosts takes them: the job's
	// InsecureChartHostsEnv, all of them.
	InsecureChartHosts []string
	// CAFile is the CA bundle (PEM) the job trusts, the platform's own
	// CA included, as a file of the runner's Docker daemon: an absolute
	// path of letters, digits, '.', '_', '-' and '/', in a directory of its
	// own. The workflow mounts that directory read-only at the same path in
	// the job's container (container.volumes: the runner has to allow it,
	// valid_volumes) and sets SSL_CERT_FILE to the file, which Go reads
	// instead of the system's certificates: the bundle holds the public CAs
	// as well. "" for none: the system's certificates.
	CAFile string
}

// checkCAFile refuses a CAFile that is not an absolute path of a file in a
// directory of its own, or holds a character that a volume entry, a YAML
// flow scalar or a shell would read.
func checkCAFile(file string) error {
	if file == "" {
		return nil
	}
	dir := path.Dir(file)
	if !path.IsAbs(file) || path.Clean(file) != file || dir == "/" || path.Base(file) == "." ||
		strings.Trim(file, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-/") != "" {
		return fmt.Errorf("%q: an absolute path of a file in a directory of its own, of letters, digits, '.', '_', '-' and '/' (the directory is mounted read-only in the job)", file)
	}
	return nil
}

// OutputWorkflowWith is OutputWorkflow, the job's environment carrying
// opts: the hosts of opts.InsecureHTTPHosts the topology needs,
// opts.PrivateChartHosts and opts.InsecureChartHosts, an entry ChartHosts
// refuses an error.
func OutputWorkflowWith(topology []byte, opts WorkflowOptions) ([]byte, error) {
	text := strings.ReplaceAll(string(topology), "\r\n", "\n")
	insecure, err := checkRunnerTopology(text, opts.InsecureHTTPHosts)
	if err != nil {
		return nil, fmt.Errorf("the topology of the workflow: %w", err)
	}
	private, err := chartHosts(opts.PrivateChartHosts)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", PrivateChartHostsEnv, err)
	}
	insecureCharts, err := chartHosts(opts.InsecureChartHosts)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", InsecureChartHostsEnv, err)
	}
	if err := checkCAFile(opts.CAFile); err != nil {
		return nil, fmt.Errorf("%s: %w", RunnerCAFileEnv, err)
	}
	volumes := fmt.Sprintf("%q", RunnerChartVolume+":"+RunnerChartCache)
	env := fmt.Sprintf("%s: ${{ secrets.%s }}", TokenEnv, TokenSecret)
	if opts.CAFile != "" {
		dir := path.Dir(opts.CAFile)
		volumes += fmt.Sprintf(", %q", dir+":"+dir+":ro")
		env += fmt.Sprintf("\n          SSL_CERT_FILE: %q", opts.CAFile)
	}
	if len(insecure) > 0 {
		env += fmt.Sprintf("\n          %s: %q", InsecureHTTPHostsEnv, strings.Join(insecure, ","))
	}
	if len(private) > 0 {
		env += fmt.Sprintf("\n          %s: %q", PrivateChartHostsEnv, strings.Join(private, ","))
	}
	if len(insecureCharts) > 0 {
		env += fmt.Sprintf("\n          %s: %q", InsecureChartHostsEnv, strings.Join(insecureCharts, ","))
	}
	var script strings.Builder
	script.WriteString(`topology="$(mktemp)"` + "\n")
	fmt.Fprintf(&script, "printf %%s '%s' | base64 -d > \"$topology\"\n", base64.StdEncoding.EncodeToString([]byte(text)))
	fmt.Fprintf(&script, `okdp-gitops compile --config "$topology" --charts %s`+"\n", RunnerChartCache)

	return fmt.Appendf(nil, `%s
name: okdp-gitops
on:
  schedule:
    - cron: %q
  workflow_dispatch: {}
concurrency:
  group: %s
  cancel-in-progress: false
jobs:
  compile:
    runs-on: %s
    container:
      volumes: [%s]
    steps:
      - name: okdp-gitops compile
        shell: sh
        env:
          %s
        run: |
%s`, GeneratedHeader, WorkflowSchedule, WorkflowConcurrencyGroup, RunnerLabel, volumes,
		env, indent(script.String(), "          ")), nil
}

// runnerURL is the URL of a part of a topology a job reaches.
type runnerURL struct {
	name string // the part: platform, projects, output
	raw  string
	u    *url.URL
}

// insecureHostsOf returns the hosts or globs of allowed that the http://
// URLs need, in the order of allowed; an http:// URL of a host none
// matches is refused.
func insecureHostsOf(urls []runnerURL, allowed []string) ([]string, error) {
	if err := checkInsecureHosts(allowed); err != nil {
		return nil, err
	}
	used := map[string]bool{}
	for _, part := range urls {
		if !strings.EqualFold(part.u.Scheme, "http") {
			continue
		}
		host := strings.ToLower(part.u.Hostname())
		matched := false
		for _, h := range allowed {
			if ok, _ := path.Match(h, host); ok {
				used[h], matched = true, true
			}
		}
		if !matched {
			return nil, fmt.Errorf("%s.url %q: the token of %s would go over http://, in clear, to %s: allow the host with %s, or use https://", part.name, part.raw, TokenSecret, host, InsecureHTTPHostsEnv)
		}
	}
	var out []string
	for _, h := range allowed {
		if used[h] && !slices.Contains(out, h) {
			out = append(out, h)
		}
	}
	return out, nil
}

// checkRunnerTopology refuses a topology a job cannot use, or that the
// workflow cannot hold as it is, parsed once; it returns the hosts or
// globs of allowed its http:// URLs need (insecureHostsOf).
func checkRunnerTopology(text string, allowed []string) ([]string, error) {
	if err := checkControlCharacters(text); err != nil {
		return nil, err
	}
	t, err := ParseTopology([]byte(text))
	if err != nil {
		return nil, err
	}
	var urls []runnerURL
	for _, part := range []struct {
		name string
		loc  Location
	}{{"platform", t.Platform}, {"projects", t.Projects}, {"output", t.Output}} {
		u, err := url.Parse(strings.ReplaceAll(part.loc.URL, ProjectPlaceholder, "p"))
		if err != nil || (u.Scheme != "https" && u.Scheme != "http") || u.Host == "" {
			return nil, fmt.Errorf("%s.url %q: the job reaches its repositories over HTTP(S), with the token of %s", part.name, part.loc.URL, TokenSecret)
		}
		if _, ok := u.User.Password(); ok {
			return nil, fmt.Errorf("%s.url: a password in a URL would be committed with the workflow: the token is %s's", part.name, TokenSecret)
		}
		urls = append(urls, runnerURL{name: part.name, raw: part.loc.URL, u: u})
	}
	return insecureHostsOf(urls, allowed)
}

// checkControlCharacters refuses text that holds a control character but a
// line feed and a tab: YAML reads a lone CR, NEL, LS or PS as a line
// break, where the shell and the file read none, so that a value broken by
// one is not the text the operator reviewed.
func checkControlCharacters(text string) error {
	line := 1
	for _, r := range text {
		switch {
		case r == '\n':
			line++
		case r == '\t':
		case unicode.IsControl(r) || r == '\u2028' || r == '\u2029':
			return fmt.Errorf("line %d holds the control character %U, which YAML may read as a line break", line, r)
		}
	}
	return nil
}

// indent prefixes each line of text that is not empty with prefix.
func indent(text, prefix string) string {
	var b strings.Builder
	for line := range strings.SplitSeq(strings.TrimSuffix(text, "\n"), "\n") {
		if line != "" {
			b.WriteString(prefix)
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}
